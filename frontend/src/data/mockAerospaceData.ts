// Helper to generate realistic CMAPSS degradation cycles
export function generateCycleHistory(
  baseCycles: number,
  finalRul: number,
  isDegraded: boolean
): CycleTelemetryPoint[] {
  const points: CycleTelemetryPoint[] = [];
  const startCycle = Math.max(1, baseCycles - 60);

  for (let c = startCycle; c <= baseCycles; c++) {
    const cycleProgress = (c - startCycle) / 60;
    // Degradation curve accelerates near end of life
    const wearFactor = isDegraded ? Math.pow(cycleProgress, 2.2) : cycleProgress * 0.25;

    const baseT24 = 642.3; // °R
    const baseT30 = 1588.0 + wearFactor * 52.0 + (Math.sin(c * 0.4) * 1.5); // °R
    const baseT50 = 1404.0 + wearFactor * 68.0 + (Math.cos(c * 0.3) * 2.1); // EGT °R
    const baseP30 = 553.8 - wearFactor * 24.0 + (Math.sin(c * 0.2) * 0.8); // psia
    const baseNf = 2388.0 - wearFactor * 18.0; // Fan rpm
    const baseNc = 9050.0 + wearFactor * 42.0; // Core rpm (rises as efficiency drops)
    const basePs30 = 47.4 - wearFactor * 3.8; // psia
    const basePhi = 521.8 + wearFactor * 14.5;
    const baseBpr = 8.42 - wearFactor * 0.38;
    const baseVib = 1.1 + wearFactor * 2.8 + (Math.random() * 0.15);

    const anomalyScore = Math.min(0.98, Math.max(0.04, 0.08 + wearFactor * 0.85 + (isDegraded ? 0.08 : 0)));
    const remainingActual = Math.max(5, Math.round(finalRul + (baseCycles - c)));
    const rfPred = Math.max(4, Math.round(remainingActual + (Math.sin(c) * 4)));
    const lstmPred = Math.max(3, Math.round(remainingActual - (Math.cos(c * 0.7) * 5)));
    const ensemble = Math.round((rfPred * 0.5) + (lstmPred * 0.5));

    points.push({
      cycle: c,
      altitude: 35000 + (Math.sin(c * 0.5) * 1200),
      machNumber: 0.82,
      throttleResolverAngle: 100,
      T24: Number(baseT24.toFixed(1)),
      T30: Number(baseT30.toFixed(1)),
      T50: Number(baseT50.toFixed(1)),
      P30: Number(baseP30.toFixed(1)),
      Nf: Number(baseNf.toFixed(1)),
      Nc: Number(baseNc.toFixed(1)),
      Ps30: Number(basePs30.toFixed(2)),
      phi: Number(basePhi.toFixed(2)),
      BPR: Number(baseBpr.toFixed(2)),
      vibration: Number(baseVib.toFixed(2)),
      anomalyScore: Number(anomalyScore.toFixed(3)),
      rulActual: remainingActual,
      rulPredictedRF: rfPred,
      rulPredictedLSTM: lstmPred,
      rulEnsemble: ensemble,
    });
  }

  return points;
}

